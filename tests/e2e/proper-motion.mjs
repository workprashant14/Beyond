import { createRequire } from "node:module";
// Needs production server on :3111. Night sky for a place, jump to dates 1000 and 2900, check the proper-motion note, axe and console.
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const axeSrc = require("fs").readFileSync(require.resolve("axe-core/axe.min.js"), "utf8");
const BASE = process.env.BASE ?? "http://localhost:3111";
const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-unsafe-swiftshader"] });
let fail = 0;
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fail++; };
const p = await (await b.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
const errs = [];
p.on("console", (m) => m.type() === "error" && !/WebGL|GPU stall|GL Driver|swiftshader/i.test(m.text()) && errs.push(m.text()));
p.on("pageerror", (e) => errs.push(String(e)));
await p.goto(`${BASE}/sky`, { waitUntil: "networkidle" });
await p.getByRole("button", { name: /Night sky/i }).click();
const panel = p.getByRole("complementary", { name: "Night sky" });
await panel.getByPlaceholder("28.61").fill("28.61");
await panel.getByPlaceholder("77.21").fill("77.21");
await panel.getByRole("button", { name: "Show this sky" }).click();
await p.waitForTimeout(800);
await p.waitForFunction(() => /2\d yr after 2000/.test(document.querySelector("[data-testid=pm-note]")?.textContent ?? ""), null, { timeout: 15000 });
ok(true, "today (2026): note says 26 yr after 2000 once motions load");
const set = async (y) => {
  await p.getByLabel("year (universal time)").fill(String(y));
  await p.getByLabel("month (universal time)").fill("1");
  await p.getByLabel("day (universal time)").fill("1");
  await p.getByLabel("hour (universal time)").fill("0");
  await p.getByLabel("minute (universal time)").fill("0");
  await panel.getByRole("button", { name: "Show this date" }).click();
};
await set(1000);
await p.getByTestId("pm-note").waitFor();
await p.waitForFunction(() => /Estimated/.test(document.querySelector("[data-testid=pm-note]")?.textContent ?? ""), null, { timeout: 15000 });
let t = await p.getByTestId("pm-note").innerText();
ok(/1,000 yr before 2000/.test(t) && /Estimated/.test(t) && /Boundaries stay fixed/.test(t), `1000: note says ${JSON.stringify(t)}`);
await set(2900);
await p.waitForFunction(() => /900 yr after 2000/.test(document.querySelector("[data-testid=pm-note]")?.textContent ?? ""), null, { timeout: 15000 });
ok(true, "2900: note updates to 900 yr after 2000");
await p.screenshot({ path: "/tmp/claude-0/pm-2900.png" });
await p.addScriptTag({ content: axeSrc });
const ax = await p.evaluate(() => axe.run(document, { runOnly: ["wcag2a", "wcag2aa"] }));
ok(ax.violations.length === 0, `axe ${ax.violations.map((v) => v.id + ":" + v.nodes.length).join(", ") || "0 violations"}`);
ok(errs.length === 0, `console errors ${JSON.stringify(errs.slice(0, 3))}`);
await b.close();
process.exit(fail ? 1 : 0);
